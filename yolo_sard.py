def run_on_video(weights: Path, src: Path, dst: Path, conf=0.35, iou=0.5):
    detector = YOLO(str(weights))
    cap = cv2.VideoCapture(str(src))

    fps = cap.get(cv2.CAP_PROP_FPS) or 30
    w = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    h = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))

    writer = cv2.VideoWriter(
        str(dst), cv2.VideoWriter_fourcc(*"mp4v"), fps, (w, h)
    )

    survivors_seen = 0
    frame_idx = 0
    while True:
        ok, frame = cap.read()
        if not ok:
            break

        result = detector.predict(
            frame, conf=conf, iou=iou, imgsz=640, device=device, verbose=False
        )[0]

        for box in result.boxes:
            x1, y1, x2, y2 = box.xyxy[0].int().tolist()
            score = float(box.conf[0])
            cv2.rectangle(frame, (x1, y1), (x2, y2), (0, 255, 0), 2)
            cv2.putText(
                frame,
                f"survivor {score:.2f}",
                (x1, max(0, y1 - 8)),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.6,
                (0, 255, 0),
                2,
            )
            survivors_seen += 1

        cv2.putText(
            frame,
            f"frame {frame_idx}  detections so far: {survivors_seen}",
            (10, 30),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.7,
            (255, 255, 0),
            2,
        )
        writer.write(frame)
        frame_idx += 1

    cap.release()
    writer.release()
    return frame_idx, survivors_seen


frames, hits = run_on_video(best_weights, VIDEO_IN, VIDEO_OUT)
print(f"processed {frames} frames, total detections: {hits}")
