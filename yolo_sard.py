def build_yaml(dataset_root: Path, out_path: Path):
    images_train = dataset_root / "images" / "train"
    images_val = dataset_root / "images" / "val"
    yaml_text = (
        f"path: {dataset_root}\n"
        f"train: {images_train.relative_to(dataset_root)}\n"
        f"val: {images_val.relative_to(dataset_root)}\n"
        f"names:\n"
        f"  0: person\n"
    )
    out_path.write_text(yaml_text)
    return out_path

